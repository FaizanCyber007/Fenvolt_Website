import type { NextConfig } from "next";

const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  {
    key: "Strict-Transport-Security",
    value: "max-age=31536000; includeSubDomains",
  },
];

const nextConfig: NextConfig = {
  // Cache Components is still experimental on the Workers runtime (its
  // prerenderer uses timers that can hang a request). Nothing on this site
  // uses `use cache`, so the site builds static without it and deploys clean.
  poweredByHeader: false,
  // Cloudflare Workers has no Sharp at runtime. The supplied stills and the
  // logo are already compressed for their display size, so serve them as-is
  // instead of depending on Cloudflare Images.
  images: { unoptimized: true },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
